export const DICTS = { en, it, de, fr, es, pt };

const STORE = "minikeyboard.lang";
let lang = "en";
let plurals = new Intl.PluralRules("en");

const lookup = (dict, key) => key.split(".").reduce((o, k) => (o == null ? undefined : o[k]), dict);

/** True if `key` names a text (in English, the fallback of every language). */
export function hasKey(key) {
  const v = lookup(en, key);
  return typeof v === "string" || (v != null && typeof v.other === "string");
}

/** The text for `key` with `{name}` placeholders filled; plural forms use `params.n`. */
export function t(key, params = {}) {
  let v = lookup(DICTS[lang], key) ?? lookup(en, key) ?? key;
  if (typeof v === "object") v = v[plurals.select(Number(params.n))] ?? v.other;
  return v.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

export const getLang = () => lang;

/** Saved choice, else the first supported entry of navigator.languages, else English. */
export function detectLang() {
  try {
    const saved = localStorage.getItem(STORE);
    if (saved && DICTS[saved]) return saved;
  } catch {}
  for (const l of navigator.languages || [navigator.language]) {
    const code = String(l || "").toLowerCase().split("-")[0];
    if (DICTS[code]) return code;
  }
  return "en";
}

/** Switch language; `persist` remembers a choice made by the user. */
export function setLang(code, persist = false) {
  lang = DICTS[code] ? code : "en";
  plurals = new Intl.PluralRules(lang);
  document.documentElement.lang = lang;
  if (persist) {
    try { localStorage.setItem(STORE, lang); } catch {}
  }
}
